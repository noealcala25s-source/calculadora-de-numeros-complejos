    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        // TODO add your handling code here:
         String cadena = lblResultado.getText();

    int i = 0;

    float real1 = 0;
    float imaginario1 = 0;
    float real2 = 0;
    float imaginario2 = 0;

    // Buscar los dos números complejos
    Pattern patron = Pattern.compile(
        "\\(([+-]?\\d+(?:\\.\\d+)?)([+-]\\d+(?:\\.\\d+)?)i\\)"
    );

    Matcher matcher = patron.matcher(cadena);

    while (matcher.find()) {

        float real = Float.parseFloat(matcher.group(1));
        float imaginario = Float.parseFloat(matcher.group(2));

        if (i == 0) {
            real1 = real;
            imaginario1 = imaginario;
        }

        if (i == 1) {
            real2 = real;
            imaginario2 = imaginario;
        }

        i++;
    }

    // Buscar la operación entre los paréntesis
    int primero = cadena.indexOf(")");
    int segundo = cadena.indexOf("(", primero);

    if (primero != -1 && segundo != -1) {

        operacion = String.valueOf(cadena.charAt(primero + 1));    }

    float real = 0;
    float imaginario = 0;

    if (i == 2) {

        if (operacion.equals("+")){
            real = real1 + real2;
            imaginario = imaginario1 + imaginario2;

        } } else if (operacion.equals("-")) {

            real = real1 - real2;
            imaginario = imaginario1 - imaginario2;

        }  else if (operacion.equals("*")) {

            real = (real1 * real2) - 
                   (imaginario1 * imaginario2);

            imaginario = (real1 * imaginario2) + 
                         (imaginario1 * real2);

        }  else if (operacion.equals("/")) {

            float denominador = 
                    (real2 * real2) + 
                    (imaginario2 * imaginario2);

            if (denominador != 0) {

                real = ((real1 * real2) + 
                        (imaginario1 * imaginario2)) 
                        / denominador;

                imaginario = ((imaginario1 * real2) - 
                              (real1 * imaginario2)) 
                              / denominador;

            } else {

                lblOperacion.setText("Error");
                return;
            }
        }

        lblOperacion.setText(
            real + " + " + imaginario + "i"
        );

    
    
    
        
    }//GEN-LAST:event_jButton1ActionPerformed

